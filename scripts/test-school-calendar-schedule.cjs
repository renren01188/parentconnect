const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");
const weekdays = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"];
const weekdayForDate = (date) => { const [year, month, day] = date.split("-").map(Number); return weekdays[new Date(Date.UTC(year, month - 1, day)).getUTCDay()]; };
const isScheduled = (date, start, end, selected = ["Mon", "Tue", "Wed", "Thu", "Fri"]) => date >= start && date <= end && selected.includes(weekdayForDate(date));
assert.equal(weekdayForDate("2026-10-19"), "Mon");
assert.equal(isScheduled("2026-10-19", "2026-10-19", "2028-12-31"), true);
assert.equal(weekdayForDate("2026-10-24"), "Sat");
assert.equal(isScheduled("2026-10-24", "2026-10-19", "2028-12-31"), false);
assert.equal(weekdayForDate("2026-10-25"), "Sun");
assert.equal(isScheduled("2026-10-25", "2026-10-19", "2028-12-31"), false);
assert.equal(isScheduled("2026-10-24", "2026-10-19", "2028-12-31", ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat"]), true);
assert.equal(weekdayForDate("2026-12-31"), "Thu");
assert.equal(isScheduled("2026-12-31", "2026-10-19", "2028-12-31"), true);
assert.equal(weekdayForDate("2027-01-01"), "Fri");
assert.equal(isScheduled("2027-01-01", "2026-10-19", "2028-12-31"), true);
assert.equal(weekdayForDate("2028-02-29"), "Tue");
assert.equal(isScheduled("2028-02-29", "2026-10-19", "2028-12-31"), true);
const calendar = read("src/lib/schoolCalendar.ts");
const schoolYearApi = read("src/app/api/school-year/route.ts");
const classSession = read("src/app/api/attendance/class-session/route.ts");
const scan = read("src/app/api/attendance/scan/route.ts");
const manual = read("src/app/api/attendance/manual/route.ts");
const absent = read("src/lib/automaticAttendanceAbsence.ts");
const monthly = read("src/app/api/attendance/monthly/route.ts");
const principalSummary = read("src/app/api/attendance/monthly-summary/route.ts");
const studentProfiles = read("src/app/dashboard/ict/StudentProfiles/page.tsx");
const migration = read("supabase/legacy-migrations/20261019110000_add_school_year_attendance_weekdays.sql");
assert.match(calendar, /Date\.UTC\(year, month - 1, day\)/);
assert.match(calendar, /getUTCDay\(\)/);
assert.match(calendar, /scheduledAttendanceDates/);
assert.match(schoolYearApi, /attendance_weekdays/);
assert.match(schoolYearApi, /hasOnlyValidAttendanceWeekdays/);
assert.match(studentProfiles, /SCHOOL_WEEKDAY_OPTIONS/);
assert.match(studentProfiles, /scheduledClassDates\.length/);
assert.match(migration, /attendance_weekdays text\[\]/);
for (const [name, source] of [["class session", classSession], ["RFID scan", scan], ["manual attendance", manual], ["automatic absence", absent], ["monthly attendance", monthly], ["principal summary", principalSummary]]) assert.match(source, /isScheduledAttendanceDate/, name + " must use the shared calendar rule.");
console.log("School calendar range and selected-day checks passed.");
