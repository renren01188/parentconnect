-- Run once in Supabase to enable ICT-reviewed Guidance Counselor profile changes.
CREATE TABLE IF NOT EXISTS public.guidance_change_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guidance_id BIGINT NOT NULL REFERENCES public.guidance_counselors(id) ON DELETE CASCADE,
  guidance_name TEXT NOT NULL,
  guidance_email TEXT NOT NULL,
  guidance_initials TEXT NOT NULL,
  changes JSONB NOT NULL DEFAULT '[]'::jsonb,
  note TEXT,
  status TEXT NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending', 'Approved', 'Rejected')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  reviewed_at TIMESTAMPTZ,
  reviewed_by_ict_id BIGINT REFERENCES public.ict_admins(id) ON DELETE SET NULL,
  review_note TEXT
);

CREATE INDEX IF NOT EXISTS guidance_change_requests_guidance_status_idx
  ON public.guidance_change_requests (guidance_id, status, created_at DESC);

-- The browser never queries this table directly. All access goes through
-- authenticated Next.js API routes using the service-role server client.
-- Keep RLS enabled and do not add public/anon policies.
ALTER TABLE public.guidance_change_requests ENABLE ROW LEVEL SECURITY;
