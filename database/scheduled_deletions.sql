-- Reversible, 30-day deletion queue. Run this migration in Supabase.
create table if not exists public.scheduled_deletions (
  id bigint generated by default as identity primary key,
  target_type text not null check (target_type in ('student', 'parent', 'adviser', 'ict')),
  target_id text not null,
  target_name text not null,
  target_email text,
  requested_by_role text not null check (requested_by_role in ('Adviser', 'ICT')),
  requested_by_id bigint not null,
  reason text not null,
  status text not null default 'PendingICT' check (status in ('PendingICT', 'Scheduled', 'Rejected', 'Restored', 'Deleted')),
  requested_at timestamptz not null default now(),
  approved_at timestamptz,
  approved_by_ict_id bigint,
  delete_after timestamptz,
  restored_at timestamptz,
  notice_sent_at timestamptz
);

create index if not exists scheduled_deletions_due_idx on public.scheduled_deletions (status, delete_after);
create unique index if not exists scheduled_deletions_one_active_target_idx
  on public.scheduled_deletions (target_type, target_id)
  where status in ('PendingICT', 'Scheduled');
