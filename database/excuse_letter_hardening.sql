-- Excuse-letter workflow hardening.
-- Apply this migration before deploying the related UI/API changes.

create table if not exists public.excuse_letter_attachments (
  id bigint generated by default as identity primary key,
  excuse_letter_id integer not null references public.excuse_letters(id) on delete cascade,
  file_name text not null check (length(btrim(file_name)) between 1 and 180),
  file_type text not null check (length(btrim(file_type)) between 1 and 120),
  file_data text not null check (length(file_data) > 0),
  created_at timestamptz not null default now()
);

create index if not exists excuse_letter_attachments_letter_id_idx
  on public.excuse_letter_attachments (excuse_letter_id);

-- Preserve attachments saved by the previous single-file implementation.
insert into public.excuse_letter_attachments (excuse_letter_id, file_name, file_type, file_data)
select id, file_name, coalesce(file_type, 'application/octet-stream'), file_data
from public.excuse_letters e
where file_name is not null
  and file_data is not null
  and not exists (
    select 1 from public.excuse_letter_attachments a
    where a.excuse_letter_id = e.id
  );

alter table public.excuse_letter_attachments enable row level security;
revoke all on table public.excuse_letter_attachments from anon, authenticated;

-- The same unfinished request cannot be submitted repeatedly by double clicks
-- or concurrent browser requests. A declined request may be corrected and
-- submitted again as a new request.
create unique index if not exists excuse_letters_one_pending_request_idx
  on public.excuse_letters (parent_id, student_id, date_from, date_to)
  where status = 'Pending';

-- A single attendance result exists per student and school day, allowing the
-- approval function below to use an atomic upsert.
create unique index if not exists attendance_logs_student_day_idx
  on public.attendance_logs (student_id, attendance_date)
  where student_id is not null;

alter table public.excuse_letters
  drop constraint if exists excuse_letters_status_check;
alter table public.excuse_letters
  add constraint excuse_letters_status_check
  check (status in ('Pending', 'Approved', 'Declined'));

-- The API calls this with the authenticated adviser's id. The row lock makes a
-- decision immutable: exactly one approve/decline request can succeed.
create or replace function public.decide_excuse_letter(
  p_letter_id integer,
  p_adviser_id integer,
  p_status text,
  p_decline_reason text default null
)
returns table (
  id integer,
  status text,
  student_id text,
  parent_id integer,
  date_from date,
  date_to date
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_letter public.excuse_letters%rowtype;
  v_student public.students%rowtype;
  v_adviser public.advisers%rowtype;
  v_date date;
  v_session_type text;
begin
  if p_status is null or p_status not in ('Approved', 'Declined') then
    raise exception 'Invalid excuse-letter status.' using errcode = 'P0001';
  end if;

  if p_status = 'Declined' and nullif(btrim(coalesce(p_decline_reason, '')), '') is null then
    raise exception 'A decline reason is required.' using errcode = 'P0001';
  end if;

  select * into v_adviser
  from public.advisers
  where id = p_adviser_id;

  if not found then
    raise exception 'Adviser not found.' using errcode = 'P0001';
  end if;

  select * into v_letter
  from public.excuse_letters
  where id = p_letter_id
  for update;

  if not found then
    raise exception 'Excuse letter not found.' using errcode = 'P0001';
  end if;

  if v_letter.status <> 'Pending' then
    raise exception 'This excuse letter has already been reviewed.' using errcode = 'P0001';
  end if;

  -- Lock the student row too, so overlapping requests for the same student are
  -- serialized while attendance is updated.
  select * into v_student
  from public.students
  where student_id = v_letter.student_id
  for update;

  if not found then
    raise exception 'Student not found.' using errcode = 'P0001';
  end if;

  if v_adviser.grade is distinct from v_student.grade
     or not (
       coalesce(v_adviser.sections, '{}'::text[]) @> array[v_student.section]
       or v_adviser.section = v_student.section
     ) then
    raise exception 'This excuse letter is not assigned to this adviser.' using errcode = 'P0001';
  end if;

  if p_status = 'Approved' then
    v_session_type := coalesce(v_student.class_session, 'Morning');

    for v_date in
      select day::date
      from generate_series(v_letter.date_from, v_letter.date_to, interval '1 day') as day
      where extract(isodow from day) < 6
    loop
      insert into public.attendance_logs (
        student_db_id, student_id, attendance_date, status, type,
        session_type, via, remark, time_logged
      ) values (
        v_student.id, v_letter.student_id, v_date, 'Excused', 'Time In',
        v_session_type, 'Auto', 'Excuse letter approved', '00:00:00'
      )
      on conflict (student_id, attendance_date) where student_id is not null do update
      set student_db_id = excluded.student_db_id,
          session_type = excluded.session_type,
          status = excluded.status,
          remark = excluded.remark;
    end loop;
  end if;

  update public.excuse_letters
  set status = p_status,
      decline_reason = case
        when p_status = 'Declined' then btrim(p_decline_reason)
        else null
      end
  where id = v_letter.id;

  return query
  select v_letter.id, p_status, v_letter.student_id, v_letter.parent_id,
         v_letter.date_from, v_letter.date_to;
end;
$$;

revoke all on function public.decide_excuse_letter(integer, integer, text, text)
  from public, anon, authenticated;
grant execute on function public.decide_excuse_letter(integer, integer, text, text)
  to service_role;
