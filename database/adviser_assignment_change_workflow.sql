-- Adviser assignment change workflow
-- Run this in the Supabase SQL editor before deploying the matching app changes.

CREATE TABLE IF NOT EXISTS public.adviser_assignment_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  adviser_id INTEGER NOT NULL REFERENCES public.advisers(id) ON DELETE CASCADE,
  request_id BIGINT REFERENCES public.adviser_change_requests(id) ON DELETE SET NULL,
  previous_grade TEXT,
  previous_sections TEXT[] NOT NULL DEFAULT '{}',
  new_grade TEXT,
  new_sections TEXT[] NOT NULL DEFAULT '{}',
  approved_by_ict_id INTEGER,
  effective_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS adviser_assignment_history_adviser_effective_idx
  ON public.adviser_assignment_history (adviser_id, effective_at DESC);

ALTER TABLE public.adviser_change_requests
  ADD COLUMN IF NOT EXISTS reviewed_by_ict_id INTEGER;

-- The application keeps the adviser record as the single current assignment.
-- Students, parents, attendance and reports are already related by each
-- student's grade/section, so they resolve the new adviser immediately from it.
