-- One parent-created report may be submitted to Guidance at most once.
-- Apply this migration in Supabase before deploying the ticket UI/API.

create table if not exists public.parent_report_guidance_tickets (
  id bigint generated by default as identity primary key,
  report_id bigint not null references public.parent_adviser_reports(id) on delete cascade,
  parent_id bigint not null references public.parents(id) on delete cascade,
  student_id text not null,
  adviser_id bigint references public.advisers(id) on delete set null,
  concern text not null,
  message text not null default '',
  attachments jsonb not null default '[]'::jsonb,
  status text not null default 'pending' check (status in ('pending', 'accepted', 'rejected')),
  rejection_reason text,
  assigned_guidance_id bigint references public.guidance_counselors(id) on delete set null,
  created_at timestamptz not null default now(),
  decided_at timestamptz,
  updated_at timestamptz not null default now(),
  constraint parent_report_guidance_tickets_one_per_report unique (report_id),
  constraint parent_report_guidance_tickets_rejection_reason check (
    status <> 'rejected' or nullif(btrim(coalesce(rejection_reason, '')), '') is not null
  )
);

create index if not exists parent_report_guidance_tickets_parent_id_idx
  on public.parent_report_guidance_tickets (parent_id);
create index if not exists parent_report_guidance_tickets_status_idx
  on public.parent_report_guidance_tickets (status, created_at desc);

alter table public.parent_report_guidance_tickets enable row level security;

-- This app authorizes through server routes using its service-role Supabase client
-- and its own signed role cookies. No browser client may read or write tickets.
revoke all on table public.parent_report_guidance_tickets from anon, authenticated;
