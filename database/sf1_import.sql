-- Run this migration in Supabase before enabling SF1 imports.
alter table public.students
  add column if not exists birth_date date,
  add column if not exists age integer,
  add column if not exists mother_tongue text,
  add column if not exists ip_ethnic_group text,
  add column if not exists religion text,
  add column if not exists house_street_sitio_purok text,
  add column if not exists barangay text,
  add column if not exists municipality_city text,
  add column if not exists province text,
  add column if not exists learning_modality text;

create table if not exists public.student_family_members (
  id bigint generated by default as identity primary key,
  student_db_id integer not null references public.students(id) on delete cascade,
  role text not null check (role in ('Father', 'Mother', 'Guardian')),
  first_name text,
  middle_name text,
  last_name text,
  relationship text,
  contact_number text,
  created_at timestamptz not null default now(),
  unique (student_db_id, role)
);

-- Father and guardian suffixes are stored separately from their names.
alter table public.student_family_members
  add column if not exists suffix text;

-- Case-insensitive, global protection for one RFID card per student.
create unique index if not exists students_rfid_card_unique_ci
  on public.students (upper(trim(rfid_card)))
  where rfid_card is not null and trim(rfid_card) <> '';
