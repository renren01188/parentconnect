-- Persist Parent-facing notices for adviser and ICT changes to a child's
-- record or to the Parent account. These are notification-feed records only:
-- they do not alter the student, Parent, attendance, report, or audit data.

BEGIN;

CREATE TABLE IF NOT EXISTS public.parent_account_change_notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id integer NOT NULL
    REFERENCES public.parents(id) ON DELETE CASCADE,
  -- Keep the LRN as a historical label rather than a foreign key: ICT can
  -- correct an LRN without invalidating the Parent's prior notification.
  student_id text,
  change_scope text NOT NULL
    CHECK (change_scope IN ('student', 'parent_account')),
  changed_fields text[] NOT NULL DEFAULT '{}',
  actor_role text NOT NULL
    CHECK (actor_role IN ('Adviser', 'ICT')),
  actor_name text NOT NULL,
  read_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS parent_account_change_notifications_parent_created_idx
  ON public.parent_account_change_notifications (parent_id, created_at DESC);

ALTER TABLE public.parent_account_change_notifications ENABLE ROW LEVEL SECURITY;

COMMENT ON TABLE public.parent_account_change_notifications IS
  'Durable Parent notification-feed records for adviser or ICT updates to a child or Parent account.';

COMMIT;
