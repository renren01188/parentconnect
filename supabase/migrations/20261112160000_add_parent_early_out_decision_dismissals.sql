BEGIN;

-- One Parent may dismiss only their own durable recipient row. The recipient
-- row is created atomically with the Guidance decision, which makes this an
-- exact Parent-account + decision key rather than a browser-local preference.
CREATE TABLE IF NOT EXISTS public.parent_early_out_decision_dismissals (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id integer NOT NULL REFERENCES public.parents(id) ON DELETE CASCADE,
  early_out_notification_id bigint NOT NULL REFERENCES public.early_out_notifications(id) ON DELETE CASCADE,
  dismissed_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  CONSTRAINT parent_early_out_decision_dismissals_one_per_parent_decision
    UNIQUE (parent_id, early_out_notification_id)
);

CREATE INDEX IF NOT EXISTS parent_early_out_decision_dismissals_parent_idx
  ON public.parent_early_out_decision_dismissals (parent_id, dismissed_at DESC);

ALTER TABLE public.parent_early_out_decision_dismissals ENABLE ROW LEVEL SECURITY;

CREATE POLICY "parent_early_out_decision_dismissals_service_role_only"
  ON public.parent_early_out_decision_dismissals
  TO service_role
  USING (true)
  WITH CHECK (true);

GRANT ALL ON TABLE public.parent_early_out_decision_dismissals TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.parent_early_out_decision_dismissals_id_seq TO service_role;

COMMIT;
