-- Keep dated SF1/SF2 remarks separately from students. A learner can have
-- more than one historical event, and each monthly SF2 export must continue
-- to reflect the event(s) saved for that month even after later changes.

BEGIN;

CREATE TABLE IF NOT EXISTS public.student_remarks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_db_id integer NOT NULL
    REFERENCES public.students(id) ON DELETE CASCADE,
  remark_type text NOT NULL
    CHECK (remark_type IN ('Dropped out', 'Transferred In', 'Transferred Out')),
  effectivity_date date NOT NULL,
  note text NOT NULL,
  school_name text,
  created_by_adviser_id integer
    REFERENCES public.advisers(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT student_remarks_required_detail CHECK (
    (remark_type = 'Dropped out'
      AND NULLIF(btrim(note), '') IS NOT NULL
      AND school_name IS NULL)
    OR
    (remark_type IN ('Transferred In', 'Transferred Out')
      AND NULLIF(btrim(note), '') IS NOT NULL
      AND NULLIF(btrim(school_name), '') IS NOT NULL)
  )
);

ALTER TABLE public.student_remarks ENABLE ROW LEVEL SECURITY;

CREATE UNIQUE INDEX IF NOT EXISTS student_remarks_student_type_date_unique
  ON public.student_remarks (student_db_id, remark_type, effectivity_date);

CREATE INDEX IF NOT EXISTS student_remarks_student_date_idx
  ON public.student_remarks (student_db_id, effectivity_date DESC, id DESC);

CREATE INDEX IF NOT EXISTS student_remarks_date_type_idx
  ON public.student_remarks (effectivity_date, remark_type);

COMMIT;
