BEGIN;

CREATE TABLE IF NOT EXISTS public.early_out_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_db_id integer NOT NULL REFERENCES public.students(id) ON DELETE RESTRICT,
  student_id text NOT NULL REFERENCES public.students(student_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  student_name text NOT NULL,
  adviser_id integer NOT NULL REFERENCES public.advisers(id) ON DELETE RESTRICT,
  adviser_name text NOT NULL,
  grade text NOT NULL,
  section text NOT NULL,
  session_type text NOT NULL CHECK (session_type IN ('Morning', 'Afternoon')),
  attendance_date date NOT NULL,
  reason text NOT NULL CHECK (char_length(btrim(reason)) BETWEEN 1 AND 500),
  message text NOT NULL CHECK (char_length(btrim(message)) BETWEEN 1 AND 2000),
  status text NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending', 'Approved', 'Rejected')),
  rejection_reason text,
  reviewed_by_guidance_id bigint REFERENCES public.guidance_counselors(id) ON DELETE RESTRICT,
  reviewed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  updated_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  CONSTRAINT early_out_requests_one_request_per_student_adviser_day UNIQUE (student_db_id, adviser_id, attendance_date),
  CONSTRAINT early_out_requests_decision_consistency CHECK (
    (status = 'Pending' AND rejection_reason IS NULL AND reviewed_by_guidance_id IS NULL AND reviewed_at IS NULL)
    OR (status = 'Approved' AND rejection_reason IS NULL AND reviewed_by_guidance_id IS NOT NULL AND reviewed_at IS NOT NULL)
    OR (status = 'Rejected' AND char_length(btrim(COALESCE(rejection_reason, ''))) > 0 AND reviewed_by_guidance_id IS NOT NULL AND reviewed_at IS NOT NULL)
  )
);

CREATE INDEX IF NOT EXISTS early_out_requests_guidance_review_idx
  ON public.early_out_requests (status, attendance_date DESC, created_at DESC);
CREATE INDEX IF NOT EXISTS early_out_requests_adviser_history_idx
  ON public.early_out_requests (adviser_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.early_out_notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  early_out_request_id bigint NOT NULL REFERENCES public.early_out_requests(id) ON DELETE CASCADE,
  recipient_role text NOT NULL CHECK (recipient_role IN ('Parent', 'Adviser')),
  recipient_id integer NOT NULL,
  read_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  CONSTRAINT early_out_notifications_one_recipient UNIQUE (early_out_request_id, recipient_role, recipient_id)
);

CREATE INDEX IF NOT EXISTS early_out_notifications_recipient_idx
  ON public.early_out_notifications (recipient_role, recipient_id, created_at DESC);

CREATE OR REPLACE FUNCTION public.decide_early_out_request(
  p_request_id bigint,
  p_guidance_id bigint,
  p_status text,
  p_rejection_reason text DEFAULT NULL
)
RETURNS TABLE (
  request_id bigint,
  request_status text,
  student_db_id integer,
  student_id text,
  attendance_date date,
  parent_notification_count integer
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_request public.early_out_requests%ROWTYPE;
  v_student public.students%ROWTYPE;
  v_time_in public.attendance_logs%ROWTYPE;
  v_time_out public.attendance_logs%ROWTYPE;
  v_request_time time;
  v_note text;
  v_parent_count integer := 0;
BEGIN
  IF p_status NOT IN ('Approved', 'Rejected') THEN
    RAISE EXCEPTION 'Early Out decisions must be Approved or Rejected';
  END IF;
  IF p_status = 'Rejected' AND char_length(btrim(COALESCE(p_rejection_reason, ''))) = 0 THEN
    RAISE EXCEPTION 'A rejection reason is required';
  END IF;

  SELECT * INTO v_request
  FROM public.early_out_requests
  WHERE id = p_request_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Early Out request not found';
  END IF;
  IF v_request.status <> 'Pending' THEN
    RAISE EXCEPTION 'This Early Out request has already been reviewed';
  END IF;

  UPDATE public.early_out_requests
  SET status = p_status,
      rejection_reason = CASE WHEN p_status = 'Rejected' THEN btrim(p_rejection_reason) ELSE NULL END,
      reviewed_by_guidance_id = p_guidance_id,
      reviewed_at = timezone('utc', now()),
      updated_at = timezone('utc', now())
  WHERE id = p_request_id;

  IF p_status = 'Approved' THEN
    SELECT * INTO v_student
    FROM public.students
    WHERE id = v_request.student_db_id
      AND student_id = v_request.student_id
    FOR UPDATE;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'The request student is no longer available';
    END IF;

    -- The request timestamp is the documented Early Out time. It is used on
    -- the request's original attendance date even when Guidance reviews later.
    v_request_time := (v_request.created_at AT TIME ZONE 'Asia/Manila')::time;
    v_note := format('Approved Early Out request #%s: %s', v_request.id, v_request.reason);

    SELECT * INTO v_time_in
    FROM public.attendance_logs
    WHERE student_db_id = v_request.student_db_id
      AND attendance_date = v_request.attendance_date
      AND session_type = v_request.session_type
      AND type = 'Time In'
    ORDER BY id DESC
    LIMIT 1
    FOR UPDATE;

    -- Preserve an RFID/manual On Time or Late arrival exactly as recorded.
    -- A prior automatic no-show is only a placeholder, so an approved Early
    -- Out replaces it with the canonical On Time arrival for this date.
    IF NOT FOUND THEN
      INSERT INTO public.attendance_logs (
        student_db_id, student_id, attendance_date, time_logged, type,
        session_type, status, via, remark
      ) VALUES (
        v_request.student_db_id, v_request.student_id, v_request.attendance_date,
        v_request_time, 'Time In', v_request.session_type, 'On Time', 'Manual', v_note
      );
    ELSIF v_time_in.status NOT IN ('Present', 'On Time', 'Late') THEN
      UPDATE public.attendance_logs
      SET status = 'On Time',
          via = 'Manual',
          remark = concat_ws(' | ', NULLIF(v_time_in.remark, ''), v_note)
      WHERE id = v_time_in.id;
    END IF;

    SELECT * INTO v_time_out
    FROM public.attendance_logs
    WHERE student_db_id = v_request.student_db_id
      AND attendance_date = v_request.attendance_date
      AND session_type = v_request.session_type
      AND type = 'Time Out'
    ORDER BY id DESC
    LIMIT 1
    FOR UPDATE;

    -- Do not overwrite a real checkout. Otherwise create/update the durable
    -- completion record that every history, summary, and SF2 reader already
    -- uses to count an attended day.
    IF NOT FOUND THEN
      INSERT INTO public.attendance_logs (
        student_db_id, student_id, attendance_date, time_logged, type,
        session_type, status, via, remark
      ) VALUES (
        v_request.student_db_id, v_request.student_id, v_request.attendance_date,
        v_request_time, 'Time Out', v_request.session_type, 'Present', 'Manual', v_note
      );
    ELSIF v_time_out.status = 'Absent' AND v_time_out.via = 'Auto' THEN
      UPDATE public.attendance_logs
      SET time_logged = v_request_time,
          status = 'Present',
          via = 'Manual',
          remark = concat_ws(' | ', NULLIF(v_time_out.remark, ''), v_note)
      WHERE id = v_time_out.id;
    END IF;
  END IF;

  -- One durable notification per authorised recipient makes retrying this
  -- RPC safe. Parent recipients are captured at decision time from both the
  -- current multi-student links and the legacy direct parent relation.
  INSERT INTO public.early_out_notifications (early_out_request_id, recipient_role, recipient_id)
  VALUES (v_request.id, 'Adviser', v_request.adviser_id)
  ON CONFLICT (early_out_request_id, recipient_role, recipient_id) DO NOTHING;

  INSERT INTO public.early_out_notifications (early_out_request_id, recipient_role, recipient_id)
  SELECT v_request.id, 'Parent', parent_id
  FROM (
    SELECT link.parent_id::integer AS parent_id
    FROM public.parent_student_links AS link
    WHERE link.student_id = v_request.student_id
    UNION
    SELECT parent.id::integer AS parent_id
    FROM public.parents AS parent
    WHERE parent.student_id = v_request.student_id
  ) AS recipients
  ON CONFLICT (early_out_request_id, recipient_role, recipient_id) DO NOTHING;

  SELECT count(*)::integer INTO v_parent_count
  FROM public.early_out_notifications
  WHERE early_out_request_id = v_request.id
    AND recipient_role = 'Parent';

  RETURN QUERY
  SELECT v_request.id, p_status, v_request.student_db_id, v_request.student_id,
    v_request.attendance_date, v_parent_count;
END;
$$;

ALTER TABLE public.early_out_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.early_out_notifications ENABLE ROW LEVEL SECURITY;

CREATE POLICY "early_out_requests_service_role_only"
  ON public.early_out_requests TO service_role USING (true) WITH CHECK (true);
CREATE POLICY "early_out_notifications_service_role_only"
  ON public.early_out_notifications TO service_role USING (true) WITH CHECK (true);

GRANT ALL ON TABLE public.early_out_requests TO service_role;
GRANT ALL ON TABLE public.early_out_notifications TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.early_out_requests_id_seq TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.early_out_notifications_id_seq TO service_role;
REVOKE ALL ON FUNCTION public.decide_early_out_request(bigint, bigint, text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.decide_early_out_request(bigint, bigint, text, text) TO service_role;

COMMIT;
